function categoryFor(name: string): Category {
  const normalizedName = name.toLocaleLowerCase('fr');

  return (
    categoryRules.find(({ keywords }) =>
      keywords.some((keyword) => normalizedName.includes(keyword)),
    )?.category ?? Category.NOTHING
  );
}

