export type SubscriptionSeed = Pick<
  Subscription,
  | 'name'
  | 'currency'
  | 'category'
  | 'startDate'
  | 'renewAfterTrial'
  | 'cancelAtPeriodEnd'
  | 'status'
> &
  Partial<
    Pick<
      Subscription,
      | 'price'
      | 'billingPeriod'
      | 'nextBillingDate'
      | 'trialEndDate'
      | 'paymentMethod'
    >
  >;

type SubscriptionSeedWithoutCategory = Omit<SubscriptionSeed, 'category'>;

function date(value: string): Date {
  return new Date(`${value}T00:00:00.000Z`);
}

function activeSubscription(
  name: string,
  price: string,
  billingPeriod: BillingPeriod,
  startDate: string,
  nextBillingDate: string,
  paymentMethod: PaymentMethod,
  currency = CurrencyCode.EUR,
  cancelAtPeriodEnd = false,
): SubscriptionSeedWithoutCategory {
  return {
    name,
    price,
    currency,
    billingPeriod,
    startDate: date(startDate),
    nextBillingDate: date(nextBillingDate),
    paymentMethod,
    renewAfterTrial: false,
    cancelAtPeriodEnd,
    status: SubscriptionStatus.ACTIVE,
  };
}

function cancelledSubscription(
  name: string,
  price: string,
  billingPeriod: BillingPeriod,
  startDate: string,
  paymentMethod: PaymentMethod,
  currency = CurrencyCode.EUR,
): SubscriptionSeedWithoutCategory {
  return {
    name,
    price,
    currency,
    billingPeriod,
    startDate: date(startDate),
    paymentMethod,
    renewAfterTrial: false,
    cancelAtPeriodEnd: false,
    status: SubscriptionStatus.CANCELLED,
  };
}

function renewableTrial(
  name: string,
  price: string,
  billingPeriod: BillingPeriod,
  startDate: string,
  trialEndDate: string,
  paymentMethod: PaymentMethod,
  currency = CurrencyCode.EUR,
): SubscriptionSeedWithoutCategory {
  return {
    name,
    price,
    currency,
    billingPeriod,
    startDate: date(startDate),
    trialEndDate: date(trialEndDate),
    paymentMethod,
    renewAfterTrial: true,
    cancelAtPeriodEnd: false,
    status: SubscriptionStatus.TRIAL,
  };
}

